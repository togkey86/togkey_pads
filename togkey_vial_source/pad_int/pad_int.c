#define MAX_ENTRY_DIGITS   8   // total digits you can type
#define MAX_ENTRY_DECIMALS 4   // digits after the point (".dddd" fits one row)

static const long P10[] = {1, 10, 100, 1000, 10000, 100000, 1000000};

static long    entry_mant   = 0;     // all typed digits as one integer
static uint8_t entry_dec    = 0;     // how many of them are after the point
static bool    entry_dot    = false; // decimal point has been pressed
static uint8_t entry_digits = 0;     // digits typed so far

static void reset_entry(void) {
    entry_mant   = 0;
    entry_dec    = 0;
    entry_dot    = false;
    entry_digits = 0;
    buffB        = 0;
}

void enterNumber(int num) {
    if (entry_digits >= MAX_ENTRY_DIGITS) return;
    if (entry_dot && entry_dec >= MAX_ENTRY_DECIMALS) return;
    if (entry_mant == 0 && num == 0 && !entry_dot) return; // ignore leading zeros
    entry_mant = entry_mant * 10 + num;
    entry_digits++;
    if (entry_dot) entry_dec++;
    buffB = (double)entry_mant / (double)P10[entry_dec];
}

void clear(void) {
    buffA = 0;
    operator = ' ';
    answer = 0;
    reset_entry();
}

void calculate(void) {
    if (operator == '+') {
        answer = buffA + buffB;
    } else if (operator == '*') {
        answer = buffA * buffB;
    } else if (operator == '-') {
        answer = buffA - buffB;
    } else if (operator == '/') {
        if (buffB != 0) {
            answer = buffA / buffB;
        } else {
            dividedByZero = true;
            zero_timer = timer_read();
            clear();
            return;
        }
    }

    if (operator == ' ') {
        buffA = buffB;   // copy BEFORE reset_entry() zeroes buffB
        answer = buffB;
        reset_entry();
        return;
    }

    buffA = answer;
    reset_entry();
    operator = ' ';
}

void setOperator(char newOp) {
    if (operator != ' ') {
        calculate();
        buffA = answer;
        reset_entry();
    } else if (newOp != ' ') {
        if (lastKeycode == KC_KP_ENTER) {
            buffA = answer;
            reset_entry();
        } else {
            buffA = buffB;   // copy BEFORE reset_entry() zeroes buffB
            reset_entry();
            answer = buffA;
        }
    }

    operator = newOp;
}

bool process_record_kb(uint16_t keycode, keyrecord_t *record) {

    // ---------- Keyboard Functions ----------
    switch (keycode) {

        case LAYER_UP:
            if (record->event.pressed) {
                uint8_t current_layer = get_highest_layer(layer_state);
                layer_move((current_layer + 1) % (max_num_layers + 1));
            }
            return false;

        case LAYER_DOWN:
            if (record->event.pressed) {
                uint8_t current_layer = get_highest_layer(layer_state);

                if (current_layer == 0) {
                    layer_move(max_num_layers);
                } else {
                    layer_move(current_layer - 1);
                }
            }
            return false;

        case MODE_NEXT:
            if (record->event.pressed) {
                numbpad_mode = (numbpad_mode + 1) % 2;
                oled_clear();
                dividedByZero = false;
                clear();        // reset calculator when changing modes
            }
            return false;

        case NUM_00:
            if (record->event.pressed) {
                if (numbpad_mode == 1) {
                    enterNumber(0);
                    enterNumber(0);
                    lastKeycode = KC_KP_0;
                } else {
                    tap_code(KC_KP_0);
                    tap_code(KC_KP_0);
                }
            }
            return false;
    }

    // ---------- Calculator ----------
    if (numbpad_mode == 1) {

        if (record->event.pressed) {

            switch (keycode) {

                case KC_KP_0: enterNumber(0); break;
                case KC_KP_1: enterNumber(1); break;
                case KC_KP_2: enterNumber(2); break;
                case KC_KP_3: enterNumber(3); break;
                case KC_KP_4: enterNumber(4); break;
                case KC_KP_5: enterNumber(5); break;
                case KC_KP_6: enterNumber(6); break;
                case KC_KP_7: enterNumber(7); break;
                case KC_KP_8: enterNumber(8); break;
                case KC_KP_9: enterNumber(9); break;

                case KC_KP_DOT:
                    entry_dot = true; // shows "5." right away as feedback
                    break;

                case KC_KP_PLUS:
                    setOperator('+');
                    break;

                case KC_KP_MINUS:
                    setOperator('-');
                    break;

                case KC_KP_ASTERISK:
                    setOperator('*');
                    break;

                case KC_KP_SLASH:
                    setOperator('/');
                    break;

                case KC_KP_ENTER:
                    if (lastKeycode == KC_KP_ENTER) {
                        clear();
                    } else {
                        calculate();
                    }
                    break;
            }

            lastKeycode = keycode;
        }

        // Don't send keypad presses to the PC while in calculator mode
        return false;
    }

    // ---------- Normal Numpad ----------
    return true;
}

// ---------- Display formatting ----------

#define NUM_BUF 24   // big enough that GCC can prove no truncation

// Writes `digits` zero-padded decimal digits of `frac` into dst (no printf,
// so there is no format-truncation warning to trip over).
static void write_frac(char *dst, long frac, uint8_t digits) {
    for (int i = (int)digits - 1; i >= 0; i--) {
        dst[i] = (char)('0' + (frac % 10));
        frac /= 10;
    }
    dst[digits] = '\0';
}

// Shows exactly what was typed: "5", "5.", "5.0", "0.005"
static void format_entry(char *out) {   // out >= NUM_BUF bytes
    if (entry_dec > 0) {
        char f[MAX_ENTRY_DECIMALS + 1];
        write_frac(f, entry_mant % P10[entry_dec], entry_dec);
        snprintf(out, NUM_BUF, "%ld.%s", entry_mant / P10[entry_dec], f);
    } else {
        snprintf(out, NUM_BUF, entry_dot ? "%ld." : "%ld", entry_mant);
    }
}

// For buffA / results: picks decimals that fit, trims trailing zeros.
// Avoids %f on purpose (newlib-nano has no float printf by default).
static void format_number(double v, char *out) {   // out >= NUM_BUF bytes
    bool neg = v < 0;
    double a = fabs(v);

    if (isnan(v) || isinf(v) || a >= 1e9) {
        strcpy(out, "OVER");
        return;
    }

    long ip = (long)a;
    uint8_t idig = 1;
    for (long t = ip; t >= 10; t /= 10) idig++;

    int dec = 9 - idig;                 // ~9 digits across two rows
    if (dec > MAX_ENTRY_DECIMALS) dec = MAX_ENTRY_DECIMALS;
    if (dec < 0) dec = 0;

    long scaled = (long)(a * (double)P10[dec] + 0.5);
    long ipart  = scaled / P10[dec];
    long fpart  = scaled % P10[dec];

    char *p = out;
    if (neg && scaled) *p++ = '-';
    p += sprintf(p, "%ld", ipart);

    if (dec > 0) {
        char f[MAX_ENTRY_DECIMALS + 1];
        write_frac(f, fpart, (uint8_t)dec);
        int n = dec;
        while (n > 0 && f[n - 1] == '0') n--;   // trim trailing zeros
        if (n > 0) {
            *p++ = '.';
            memcpy(p, f, n);
            p += n;
        }
    }
    *p = '\0';
}

// Right-aligned, 5 characters wide
static void print_row(uint8_t row, const char *s) {
    char b[6];
    size_t n = strlen(s);
    if (n > 5) n = 5;
    memset(b, ' ', 5);
    memcpy(b + 5 - n, s, n);
    b[5] = '\0';
    oled_set_cursor(0, row);
    oled_write(b, false);
}

// Uses two rows (row and row+1). Splits at the decimal point.
static void print_number(uint8_t row, const char *s) {
    const char *dot = strchr(s, '.');
    char top[6];

    if (strlen(s) <= 5) {
        print_row(row, s);
        print_row(row + 1, "");
    } else if (dot && (dot - s) <= 5) {
        size_t n = dot - s;
        memcpy(top, s, n);
        top[n] = '\0';
        print_row(row, top);
        print_row(row + 1, dot);
    } else {                                    // long integer: hard split
        memcpy(top, s, 5);
        top[5] = '\0';
        print_row(row, top);
        print_row(row + 1, s + 5);
    }
}

void render_calc_mode_128x32(void) {
    char buf[NUM_BUF];

    // Clear the error flag once its message has been shown
    if (dividedByZero && timer_elapsed(zero_timer) >= 750) {
        dividedByZero = false;
    }

    // Rows 0-1: header
    oled_set_cursor(0, 0);
    oled_write_P(PSTR("CALC"), false);
    oled_set_cursor(0, 1);
    oled_write_P(PSTR("-----"), false);

    // Row 2: blank spacer

    // Rows 3-4: first number
    format_number(buffA, buf);
    print_number(3, buf);

    // Row 5: operator
    char opBuf[2] = { (operator != ' ' && operator != '\0') ? operator : ' ', '\0' };
    print_row(5, opBuf);

    // Rows 6-7: number being typed
    format_entry(buf);
    print_number(6, buf);

    // Row 8: equals line
    oled_set_cursor(0, 8);
    oled_write_P(PSTR("====="), false);

    // Row 9: blank spacer

    // Rows 10-11: result
    if (dividedByZero) {
        print_row(10, "ERR!");
        print_row(11, "");
    } else {
        format_number(answer, buf);
        print_number(10, buf);
    }

    // Row 12: blank spacer

    // Rows 13-14: status (row 15 left blank as a bottom margin)
    oled_set_cursor(0, 13);
    oled_write_P(PSTR("-----"), false);
    oled_set_cursor(0, 14);
    if (dividedByZero) {
        oled_write_P(PSTR("ERROR"), false);
    } else if (operator != ' ' && operator != '\0') {
        oled_write_P(PSTR("BUSY "), false);
    } else {
        oled_write_P(PSTR("READY"), false);
    }
}

